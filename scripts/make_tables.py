"""Write results/tables.md from results/summary.json (the tables quoted in README and DOSSIER)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def pc(x) -> str:
    return "-" if x is None else f"{100 * x:.0f}"


def num(x, nd=1) -> str:
    return "-" if x is None else f"{x:.{nd}f}"


def build(d: dict) -> str:
    dg, cv = d["diagnosis"], d["cov"]
    L = dg["levels"]
    out = ["# Result tables", "", "Generated by `scripts/run_all.py` from `results/summary.json`. Simulated.", ""]

    out += ["## T1. Right class ranked first / right and certain, % of runs", "",
            f"{dg['runs_per_class']} randomised installations per class, 4 h window each.", "",
            "| Fault | " + " | ".join(L) + " | First level certain in >= 90 % |",
            "|---|" + "---|" * (len(L) + 1)]
    for f in dg["faults"]:
        cells = [f"{pc(dg['recall'][lv][f])} / {pc(dg['certain_and_right'][lv][f])}" for lv in L]
        out.append(f"| {f} | " + " | ".join(cells) + f" | {dg['first_certain_level'][f] or 'never'} |")
    out += ["", "| Level | Mean right first (%) | Certain verdicts right | Certain verdicts wrong |", "|---|---|---|---|"]
    for lv in L:
        cvd = dg["certain_verdicts"][lv]
        out.append(f"| {lv} | {pc(dg['mean_recall'][lv])} | {cvd['right']} | {cvd['wrong']} |")
    out.append("")

    out += ["## T2. Look-alikes: injected fault ranked as another class in >= 20 % of runs", "",
            "| Level | Injected | Ranked first as | Share |", "|---|---|---|---|"]
    for lv in L:
        for a, b, s in dg["lookalikes"][lv]:
            out.append(f"| {lv} | {a} | {b} | {pc(s)} % |")
    out.append("")

    out += ["## T3. Confusion matrix at E1 (rows injected, columns ranked first)", ""]
    fs = dg["faults"]
    out.append("| injected \\ said | " + " | ".join(str(i + 1) for i in range(len(fs))) + " |")
    out.append("|---|" + "---|" * len(fs))
    for i, f in enumerate(fs):
        out.append(f"| {i + 1} {f} | " + " | ".join(str(dg["confusion"]["E1"][f].get(g, 0) or "") for g in fs) + " |")
    out.append("")

    out += ["## T4. COV increment sweep (one object, 24 h, client does not renew)", "",
            f"{cv['seeds']} signal days per row. Missed = KNX value changes the client never shows. "
            "Stale = longest time the shown value differs from the KNX value. p99 error is time-weighted.", "",
            "| Signal | Increment | Changes per h | Notifications per h | Missed (%) | p99 error | Max error | Longest stale (h) | Missed with 1800 s renewal (%) |",
            "|---|---|---|---|---|---|---|---|---|"]
    for name in ("temperature", "power", "switch"):
        for r, rr in zip(cv["increment_sweep"][name], cv["increment_sweep_renew_1800s"][name]):
            inc = "any change" if r["increment"] is None else f"{r['increment']:g}"
            out.append(f"| {name} | {inc} | {num(r['changes_per_h'])} | {num(r['notifications_per_h'], 2)} | "
                       f"{pc(r['missed_share'])} | {num(r['err_p99'], 2)} | {num(r['err_max'], 2)} | "
                       f"{num(r['stale_max_s'] / 3600, 2)} | {pc(rr['missed_share'])} |")
    out.append("")

    out += ["## T5. Notification traffic of a whole gateway (messages per second)", "",
            f"Object mix (assumption): {cv['traffic_mix_assumption']}. Confirmed = notification plus acknowledge.", "",
            "| Setting | per object per h | 150 obj. unconf. / conf. | 500 obj. | 2000 obj. |", "|---|---|---|---|---|"]
    t = cv["traffic"]
    for k, v in t.items():
        if k.startswith("polling"):
            continue
        out.append(f"| COV {k} | {num(v['per_object_per_h'], 2)} | " + " | ".join(
            f"{num(v[n]['unconfirmed_msg_per_s'], 2)} / {num(v[n]['confirmed_msg_per_s'], 2)}" for n in ("150", "500", "2000")) + " |")
    out.append("| Polling 60 s, one ReadProperty per object | - | " + " | ".join(
        num(t["polling_60s_rp"][n], 2) for n in ("150", "500", "2000")) + " |")
    out.append("| Polling 60 s, 20 objects per ReadPropertyMultiple | - | " + " | ".join(
        num(t["polling_60s_rpm_20"][n], 2) for n in ("150", "500", "2000")) + " |")
    out.append("")

    out += ["## T6. Polling sweep (one object, 24 h)", "",
            "| Signal | Interval (s) | Requests per h | Missed (%) | p99 error | Max error |", "|---|---|---|---|---|---|"]
    for name, rows in cv["polling_sweep"].items():
        for r in rows:
            out.append(f"| {name} | {r['period_s']:.0f} | {num(r['requests_per_h'])} | {pc(r['missed_share'])} | "
                       f"{num(r['err_p99'], 2)} | {num(r['err_max'], 2)} |")
    out.append("")

    out += ["## T7. COV against polling", "",
            "Shortest polling interval (of 10, 30, 60, 120, 300, 600, 900, 1800, 3600 s) at which polling is worse than COV.", "",
            "| COV setting | COV missed (%) | COV p99 error | COV notifications per h | Polling misses more from (s) | Polling p99 error larger from (s) |",
            "|---|---|---|---|---|---|"]
    for k, v in cv["cov_vs_polling"].items():
        out.append(f"| {k} | {pc(v['cov_missed_share'])} | {num(v['cov_err_p99'], 2)} | {num(v['cov_notifications_per_h'], 2)} | "
                   f"{num(v['poll_worse_missed_from_s'], 0)} | {num(v['poll_worse_err_p99_from_s'], 0)} |")
    out.append("")

    out += ["## T8. After the gateway's COV settings are saved (150 objects, 6 h, save at 2 to 3 h)", "",
            "| Client renewal | Mean stale (min) | Longest stale (min) | KNX changes after the save never reported (%) | "
            "Reset BMS command unseen, mean (min) | Renewal traffic (msg/s) |", "|---|---|---|---|---|---|"]
    for r in cv["save_study"]:
        lab = "never (lifetime 0)" if r["renew_s"] is None else f"{r['renew_s']:.0f} s"
        out.append(f"| {lab} | {num(r['stale_mean_s'] / 60)} | {num(r['stale_max_s'] / 60)} | {pc(r['changes_lost_share'])} | "
                   f"{num(r['command_reset_unseen_mean_s'] / 60)} | {num(r['renewal_msg_per_s'], 3)} |")
    out.append("")

    out += ["## T9. Model check: COV on a random walk", "",
            "Mean time to move by the increment a from the last report is a^2 / sigma^2.", "",
            "| Increment | Simulated per h | Theory per h | Relative error (%) |", "|---|---|---|---|"]
    for r in cv["brownian_check"]:
        out.append(f"| {r['increment']} | {num(r['rate_sim_per_h'], 2)} | {num(r['rate_theory_per_h'], 2)} | "
                   f"{num(100 * r['relative_error'])} |")
    out.append("")

    out += ["## T10. Sensitivity", "", "| Variant | Temp. COV 0.2 K missed (%) | Polling worse (missed) from (s) | "
            "Polling worse (p99 error) from (s) | Switch polling 60 s missed (%) |", "|---|---|---|---|---|"]
    base_t = {r["increment"]: r for r in cv["increment_sweep"]["temperature"]}
    sw60 = next(r for r in cv["polling_sweep"]["switch"] if r["period_s"] == 60)
    b = cv["cov_vs_polling"]["temperature_0.2K"]
    out.append(f"| base | {pc(base_t[0.2]['missed_share'])} | {num(b['poll_worse_missed_from_s'], 0)} | "
               f"{num(b['poll_worse_err_p99_from_s'], 0)} | {pc(sw60['missed_share'])} |")
    for k, s in cv["sensitivity"].items():
        r = {x["increment"]: x for x in s["increment_sweep"]["temperature"]}
        sw = next(x for x in s["polling_sweep"]["switch"] if x["period_s"] == 60)
        c = s["cov_vs_polling_temperature_0.2K"]
        out.append(f"| {k} | {pc(r[0.2]['missed_share'])} | {num(c['poll_worse_missed_from_s'], 0)} | "
                   f"{num(c['poll_worse_err_p99_from_s'], 0)} | {pc(sw['missed_share'])} |")
    out.append("")
    out += ["Diagnosis with a different window length (mean right-first share over 11 classes, %):", "",
            "| Window | E1 | E2 | E3 | E4 | Certain wrong |", "|---|---|---|---|---|---|"]
    out.append(f"| 4 h (base) | " + " | ".join(pc(dg["mean_recall"][lv]) for lv in L) +
               f" | {dg['certain_total']['wrong']} |")
    for k, s in dg["window_sensitivity"].items():
        w = sum(v["wrong"] for v in s["certain_verdicts"].values())
        out.append(f"| {k} ({s['runs_per_class']} runs per class) | " + " | ".join(pc(s["mean_recall"][lv]) for lv in L) + f" | {w} |")
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    d = json.loads((ROOT / "results" / "summary.json").read_text(encoding="utf-8"))
    (ROOT / "results" / "tables.md").write_text(build(d), encoding="utf-8")
